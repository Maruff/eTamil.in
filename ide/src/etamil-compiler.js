// Bridge to the eTamil compiler front end, compiled to wasm.
//
// Deliberately knows nothing about CodeMirror: the diagnostics and completions
// here are the compiler's own output, and a second editor shell should be able
// to consume them without going through this file's neighbours. The CodeMirror
// adapters live in etamil-intelligence.js.
//
// The wasm is loaded on the main thread rather than in a Web Worker. Lexing,
// parsing and type-checking a source file of the size anyone edits by hand runs
// in well under a millisecond, so the postMessage round trip would cost more
// than the work. The completion model, when it arrives, is the opposite case
// and does belong in a Worker.

import init, {
  diagnostics as wasmDiagnostics,
  symbols as wasmSymbols,
  symbols_at as wasmSymbolsAt,
  script_spans as wasmScriptSpans,
  run as wasmRun,
  run_project as wasmRunProject,
  version as wasmVersion,
} from '../wasm/etamil_compiler.js'
// `?url` keeps the wasm a separate fetch rather than a base64 blob inside the
// bundle: it streams, it caches on its own, and it does not inflate the JS the
// editor needs before it can render. ide/wasm is generated by `npm run wasm`.
import wasmUrl from '../wasm/etamil_compiler_bg.wasm?url'

let readyPromise = null

/** Resolves once the wasm module is instantiated. Safe to call repeatedly. */
export function ready() {
  if (!readyPromise) {
    readyPromise = init({ module_or_path: wasmUrl }).then(() => true)
  }
  return readyPromise
}

/** True once the module is usable, so callers can skip work before then. */
let loaded = false
ready().then(() => {
  loaded = true
})

export function isLoaded() {
  return loaded
}

/**
 * Diagnostics for one source string.
 *
 * Each entry is `{ line, column, length, severity, stage, message }` with
 * 1-based line and column counted in characters, and a bilingual message
 * straight from the compiler's own error types.
 *
 * Returns an empty array before the module has loaded rather than throwing --
 * the editor should show no errors while starting up, not break.
 */
export function diagnostics(source) {
  if (!loaded) return []
  try {
    return JSON.parse(wasmDiagnostics(source))
  } catch {
    // A panic in the front end must not take the editor with it.
    return []
  }
}

/**
 * Completion candidates for one source string: `{ name, kind, detail }`.
 *
 * The compiler falls back to the identifiers in the token stream when the file
 * does not parse, so this keeps returning useful names mid-statement.
 */
export function symbols(source) {
  if (!loaded) return []
  try {
    return JSON.parse(wasmSymbols(source))
  } catch {
    return []
  }
}

/**
 * Completion candidates visible from one position: `{ name, kind, detail }`.
 *
 * Same as `symbols` minus the names that are out of scope -- another
 * function's parameters and locals. `line` and `column` are 1-based and count
 * characters, matching how the compiler positions everything else.
 */
export function symbolsAt(source, line, column) {
  if (!loaded) return []
  try {
    return JSON.parse(wasmSymbolsAt(source, line, column))
  } catch {
    return []
  }
}

/**
 * Compile and run a program. The whole pipeline runs in the browser.
 *
 * Returns `{ ok, output, error, stage, files }`. `output` is present even when
 * `ok` is false: a program that prints three lines and then fails should still
 * show its three lines. `stage` is "lex", "parse", "type" or "run".
 *
 * Files the program writes live in memory for the duration of the run and are
 * listed in `files`; nothing touches the user's disk.
 */
export function runProgram(source) {
  if (!loaded) {
    return { ok: false, output: '', error: 'compiler still loading', stage: 'run', files: [] }
  }
  try {
    return JSON.parse(wasmRun(source))
  } catch (e) {
    // A Rust panic traps the instance rather than throwing something catchable
    // on the Rust side, so this is the outer net.
    return { ok: false, output: '', error: String(e), stage: 'run', files: [] }
  }
}

/**
 * Compile and run a project: several sources that import each other.
 *
 * `files` is an object from path to source and `entry` names the one to run. An
 * `இறக்கு "vari.qmz"` finds `vari.qmz` among the others, relative to the importing file;
 * nothing outside `files` can be imported, so a program that wants the standard library
 * needs its sources in the object (see etamil-run-core.js). Same result as `runProgram`.
 */
export function runProjectSources(files, entry, input = '') {
  if (!loaded) {
    return { ok: false, output: '', error: 'compiler still loading', stage: 'run', files: [] }
  }
  try {
    return JSON.parse(wasmRunProject(JSON.stringify(files), entry, input))
  } catch (e) {
    return { ok: false, output: '', error: String(e), stage: 'run', files: [] }
  }
}

/** Version of the compiler this wasm was built from, or null before load. */
export function compilerVersion() {
  return loaded ? wasmVersion() : null
}

/**
 * Every span of ASCII that should be drawn in the eTamil font.
 *
 * Each entry is `{ line, start, end }` with a 0-based line and UTF-16 offsets
 * into it, which is what a CodeMirror document counts in.
 *
 * The rules are normative -- `docs/reference/SCRIPT_RULES.md` -- and this is
 * the compiler reading them, so the browser editor and the VS Code extension
 * cannot drift apart on which ASCII is eTamil and which is English.
 *
 * Returns an empty array before the module has loaded, as the others do: no
 * spans means everything draws in the editor's own font, which is the ordinary
 * view of the file rather than a broken one.
 */
export function scriptSpans(source) {
  if (!loaded) return []
  try {
    return JSON.parse(wasmScriptSpans(source))
  } catch {
    return []
  }
}
